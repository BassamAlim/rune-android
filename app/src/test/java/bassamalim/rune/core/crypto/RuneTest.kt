package bassamalim.rune.core.crypto

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class RuneTest {

    private fun hex(text: String) = text.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
    private fun ByteArray.hex() = joinToString("") { "%02x".format(it) }

    /** The contract with the desktop app: the same file, generated by the Rust core. */
    @Test
    fun `matches the shared vectors`() {
        val vectors = Json.parseToJsonElement(
            javaClass.getResource("/vectors.json")!!.readText()
        ).jsonArray
        assertTrue(vectors.isNotEmpty())

        for (vector in vectors) {
            val v = vector.jsonObject
            fun text(name: String) = v.getValue(name).jsonPrimitive.content
            fun number(name: String) = v.getValue(name).jsonPrimitive.int

            val secret = hex(text("secretKey"))
            val master = Rune.masterKey(text("masterPassword"), secret)
            val site = Rune.siteKey(master, text("site"), text("login"), number("counter"))

            assertEquals(text("masterKey"), master.hex())
            assertEquals(text("fingerprint"), Rune.fingerprint(master))
            assertEquals(text("siteKey"), site.hex())
            assertEquals(text("password"), Rune.password(site, number("length"), text("classes")))
            assertEquals(text("secretKeyText"), Rune.encodeSecretKey(secret))
            assertArrayEquals(
                secret,
                Rune.decodeSecretKey(text("secretKeyText").lowercase().replace(' ', '-'))
            )
        }
    }

    @Test
    fun `refuses a bad policy`() {
        val key = ByteArray(32)
        assertThrows(IllegalArgumentException::class.java) { Rune.password(key, 3, "luds") }
        assertThrows(IllegalArgumentException::class.java) { Rune.password(key, 65, "luds") }
        assertThrows(IllegalArgumentException::class.java) { Rune.password(key, 20, "") }
        assertThrows(IllegalArgumentException::class.java) { Rune.password(key, 20, "lx") }
    }

    @Test
    fun `refuses text that is not a secret key`() {
        assertNull(Rune.decodeSecretKey(""))
        assertNull(Rune.decodeSecretKey("AAAA AAAA"))
        assertNull(Rune.decodeSecretKey("1".repeat(52)))
        // 52 valid letters whose spare bits aren't zero: a mistyped last character.
        assertNull(Rune.decodeSecretKey("A".repeat(51) + "B"))
    }

    @Test
    fun `estimates strength`() {
        assertEquals(125.0, Math.round(Rune.entropyBits(20, "luds")).toDouble(), 0.0)
        assertEquals(0.0, Rune.entropyBits(20, ""), 0.0)
    }
}
